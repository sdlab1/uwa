//! Walks the workspace `providers/` directory and generates a Rust module
//! that embeds every entry file. Keeping the registry as plain files in
//! the repo (rather than a Rust literal) is what lets `uwa providers diff`
//! show a human-readable patch between the built-in and cached copies.
//!
//! Missing directory or malformed names are hard errors: a release that
//! forgets to include a provider file would silently degrade to a
//! "no registry" build, and that failure mode is invisible until a user
//! hits a stale selector.

use std::fs;
use std::path::{Path, PathBuf};

/// Hard-fail the build with a readable message. The forbid-level clippy
/// lints ban `expect`/`panic!` even in build scripts, and this generator
/// must fail loudly (a silent "no registry" build would ship broken
/// selectors), so the escape hatch is an explicit exit with panic's code.
fn die(msg: &str) -> ! {
    eprintln!("crates/uwa-config/build.rs: {msg}");
    std::process::exit(101);
}

fn env_or_die(key: &str) -> String {
    match std::env::var(key) {
        Ok(v) => v,
        Err(_) => die(&format!("env `{key}` is not set")),
    }
}

fn main() {
    let manifest_dir = env_or_die("CARGO_MANIFEST_DIR");
    let workspace = match PathBuf::from(&manifest_dir).parent().and_then(Path::parent) {
        Some(ws) => ws.to_path_buf(),
        None => die("cannot derive the workspace root from CARGO_MANIFEST_DIR"),
    };
    let registry_dir = workspace.join("providers");

    println!("cargo:rerun-if-changed={}", registry_dir.display());
    println!("cargo:rerun-if-changed=build.rs");

    let out_dir = env_or_die("OUT_DIR");
    let out_path = Path::new(&out_dir).join("registry_generated.rs");

    let mut entries: Vec<(String, PathBuf)> = Vec::new();
    if registry_dir.exists() {
        let dir_iter = match fs::read_dir(&registry_dir) {
            Ok(it) => it,
            Err(e) => die(&format!("read providers/: {e}")),
        };
        for entry in dir_iter {
            let entry = match entry {
                Ok(e) => e,
                Err(e) => die(&format!("read providers/ dir entry: {e}")),
            };
            let path = entry.path();
            if path.extension().and_then(|s| s.to_str()) != Some("toml") {
                continue;
            }
            let stem = match path.file_stem().and_then(|s| s.to_str()) {
                Some(s) => s.to_string(),
                None => die(&format!("malformed provider file name: {}", path.display())),
            };
            if stem == "manifest" {
                continue;
            }
            entries.push((stem, path));
        }
    }
    entries.sort_by(|a, b| a.0.cmp(&b.0));

    let mut src = String::new();
    src.push_str("// @generated by crates/uwa-config/build.rs\n");
    src.push_str("// Source of truth: `providers/*.toml` at the workspace root.\n\n");

    src.push_str("/// Every registry entry embedded at build time, as\n");
    src.push_str("/// `(name, file_contents)`. The name is the file stem.\n");
    src.push_str("pub const BUILTIN_ENTRIES: &[(&str, &str)] = &[\n");
    for (name, path) in &entries {
        println!("cargo:rerun-if-changed={}", path.display());
        let abs = path.canonicalize().unwrap_or_else(|_| path.clone());
        src.push_str(&format!(
            "    (\"{name}\", include_str!(\"{path}\")),\n",
            name = name,
            path = abs.display()
        ));
    }
    src.push_str("];\n\n");

    // The manifest is optional; an empty registry is legal for tests.
    let manifest_path = registry_dir.join("manifest.toml");
    if manifest_path.exists() {
        println!("cargo:rerun-if-changed={}", manifest_path.display());
        let abs = manifest_path
            .canonicalize()
            .unwrap_or_else(|_| manifest_path.clone());
        src.push_str(&format!(
            "pub const BUILTIN_MANIFEST: Option<&str> = Some(include_str!(\"{}\"));\n",
            abs.display()
        ));
    } else {
        src.push_str("pub const BUILTIN_MANIFEST: Option<&str> = None;\n");
    }

    if let Err(e) = fs::write(&out_path, src) {
        die(&format!("write {}: {e}", out_path.display()));
    }
}
