//! Clients that are configured entirely by environment variables.
//!
//! We write a single shell file to `~/.uwa/clients/env.sh` and print
//! the `source` line. We never write to `~/.bashrc` / `~/.zshrc` —
//! modifying a user's shell startup without asking is not what `uwa
//! clients install` should do.

use anyhow::{Context, Result};
use std::path::PathBuf;

use super::{paths, Payload};

pub fn path() -> PathBuf {
    paths::uwa_home().join("clients").join("env.sh")
}

pub fn patched() -> bool {
    path().exists()
}

pub fn install(payload: &Payload) -> Result<PathBuf> {
    let p = path();
    if let Some(parent) = p.parent() {
        std::fs::create_dir_all(parent)?;
    }
    let body = format!(
        r#"# Generated by `uwa clients install`. Safe to source.
#
# Do not edit by hand — `uwa clients install` rewrites this file. Put
# your own shell overrides in a different file that sources this one
# first, or in your shell's rc.

export OPENAI_BASE_URL={base_v1}
export OPENAI_API_BASE={base_v1}
export OPENAI_API_KEY={key}

export ANTHROPIC_BASE_URL={origin}
export ANTHROPIC_API_KEY={key}
export ANTHROPIC_MODEL={model}

export UWA_BASE_URL={origin}
export UWA_API_KEY={key}
export UWA_MODEL={model}
"#,
        base_v1 = payload.base_url,
        origin = payload.origin,
        key = payload.api_key,
        model = payload.model,
    );
    std::fs::write(&p, body).with_context(|| format!("write {}", p.display()))?;
    Ok(p)
}

pub fn uninstall() -> Result<Option<PathBuf>> {
    let p = path();
    if p.exists() {
        std::fs::remove_file(&p)?;
        Ok(Some(p))
    } else {
        Ok(None)
    }
}
