#!/usr/bin/env bash
# Задачи по итогам ревизии 2026-10-24:
#   (1) единый workflow выдачи задач — без ручной раздачи lead'ом и без self-service;
#   (4) обязательная идентификация агента ("какая ты модель") + учёт.
# Времена: T-232..T-236.
set -u
D=/home/user/project_uwa/target/debug/devh
cd /home/user/project_uwa || exit 1

add() {
  echo "=== ADD $1 ==="
  shift
  "$D" orch add "$@" || echo "!!! FAIL: $*"
}

# --- Идентификация: обязательная декларация модели/рантайма -------------------
add T-232 \
  --agent beam2 --p 1 --c 3 --prio 0 \
  --title "ИДЕНТИФИКАЦИЯ v2 (1/3): обязательная декларация модели/рантайма — fail-closed без декларации" \
  --zone devharness/src/core/agent_identity.rs \
  --dod "Новый модуль core/agent_identity.rs (без правок существующих файлов): декларация модели/рантайма агента (model, runtime, source) + проверки. Правила: (1) ОДИН канон = ОДИН ключ сессии: если второй ключ закрепляет то же имя — отказ (fail-closed), не тихое слияние; (2) агент БЕЗ декларации модели не получает задач (потолок C0) и не может быть lead; (3) модель, которой нет в таблице потолков => C1 (fail-closed, НЕ дефолт C5); (4) роль lead выдаётся ТОЛЬКО явной записью role=lead в реестре — идентичность/слот/алиас прав не дают; (5) смена модели фиксируется как событие (model_change) с меткой подозрения и понижением P очереди." \
  --dod ">=8 юнит-тестов: два ключа на один канон (отказ), без декларации (C0), неизвестная модель (C1), роль не выводится из identity, смена модели помечается." \
  --check "cargo test -p devh --lib core::agent_identity"

# --- Учёт: журнал идентичностей + сверка «декларация vs реестр» ---------------
add T-233 \
  --agent beam3 --p 1 --c 3 --prio 0 \
  --title "ИДЕНТИФИКАЦИЯ v2 (2/3): журнал идентичностей + сверка декларации с реестром (who is who)" \
  --zone devharness/src/core/identity_ledger.rs \
  --dod "Новый модуль core/identity_ledger.rs: append-only журнал .harness/orch/identities.jsonl (события declare/claim/model_change/role_change/task_start/task_done; поля ts, agent, key, label, source, model, runtime), дедупликация по (key,event) и ограничение размера с ротацией." \
  --dod "Сверка: функция reconcile сверяет декларацию модели с записью агента в реестре оркестратора; расхождение => пометка 'модель не подтверждена' + fail-closed (потолок C0 до подтверждения), НЕ тихий downgrade." \
  --dod ">=6 юнит-тестов: запись/чтение журнала, дедуп, ротация, расхождение модели, корректное совпадение." \
  --check "cargo test -p devh --lib core::identity_ledger"

# --- Единый workflow: автоматический выбор следующей задачи ------------------
add T-234 \
  --agent kilo-2ba65640 --p 1 --c 3 --prio 0 \
  --title "ЕДИНЫЙ WORKFLOW (1/2): dispatch — автоматический выбор следующей готовой задачи (без буфера-lead и ручной раздачи)" \
  --zone devharness/src/core/dispatch.rs \
  --dod "Новый модуль core/dispatch.rs: единый выбор СЛЕДУЮЩЕЙ задачи для агента. Фильтры: deps Done; C задачи <= потолка модели агента (fail-closed для неизвестной модели); зоны не пересекаются с активными задачами (в т.ч. своими); статус queued. Порядок детерминированный: prio, затем P, затем возраст (старые first), затем id. Результат — РОВНО ОДНА задача или пусто (actionable сообщение, без паники)." \
  --dod "Пул задач — ЕДИНЫЙ: задачи из 'буфера ведущего' не выделяются в отдельную очередь lead, а участвуют в общем отборе наравне (lead-буфер перестаёт быть источником ручной раздачи)." \
  --dod "Чистая функция + структура отчёта (task_id + причина отказа для отброшенных) => тестируема без реестра." \
  --dod ">=8 юнит-тестов: детерминизм порядка, отказ по C-потолку, отказ по пересечению зон, учёт deps, пустой пул, стабильность при одинаковых prio." \
  --check "cargo test -p devh --lib core::dispatch"

# --- Интеграция: единая команда devh next ------------------------------------
add T-235 \
  --agent beam2 --p 2 --c 3 --prio 0 \
  --dep T-232 --dep T-233 --dep T-234 --dep T-133 \
  --title "ЕДИНЫЙ WORKFLOW (2/2): devh next выдаёт задачу сам; self-service из буфера lead удалён" \
  --zone devharness/src/commands/next.rs --zone devharness/src/commands/orch.rs --zone devharness/src/core/mod.rs \
  --dod "devh next — единая точка входа: (1) требует декларацию модели (иначе actionable-ошибка с ТОЧНОЙ командой декларации); (2) сам claim'ает и стартует следующую готовую задачу по core::dispatch (start+worktree выдаются агентом, lead ничего не раздаёт вручную); (3) печатает РОВНО ОДНУ следующую команду (канон T-178); (4) не падает на пустом пуле." \
  --dod "devh orch start <ID> из буфера ведущего больше НЕ переписывает задачу на вызывающего (self-service из lead-буфера удалён); выдача идёт только через dispatch." \
  --dod "task.model/task.model_source проставляются при старте из декларации агента." \
  --dod "devh orch board показывает роль, декларированную модель/рантайм, источник декларации и расхождение 'реестр vs декларация' как ПРЕДУПРЕЖДЕНИЕ." \
  --dod "Перед правкой orch.rs дождись T-133 (та же зона) — иначе конфликт." \
  --dod ">=6 юнит-тестов в commands::next + >=2 интеграционных в devharness/tests/orch_*.rs." \
  --check "cargo test -p devh --lib commands::next"

# --- Сторож коллизий идентичности -------------------------------------------
add T-236 \
  --agent beam3 --p 1 --c 3 --prio 0 \
  --title "СТОРОЖ ИДЕНТИЧНОСТЕЙ: один канон = один ключ (guard на коллизии слотов/сессий)" \
  --zone devharness/src/core/guards/identity_guard.rs --zone devharness/src/core/guards/mod.rs \
  --dod "Guard (core/guards/identity_guard.rs): проверяет привязки идентичностей (/tmp/devh-msg/agents/*.json): каждый канон принадлежит ровно ОДНОМУ ключу; коллизия (два ключа -> одно имя) => КРИТИЧЕСКАЯ проблема (не предупреждение) с перечислением ключей и канона." \
  --dod "Guard также ловит: слот-привязка с claimed=true (общее имя для разных сессий) и алиас, указывающий на имя другого агента." \
  --dod "Guard ничего не меняет в реестре и в привязках; только диагностика (путь+строка+причина+код)." \
  --dod "Зарегистрирован в core/guards/mod.rs и вызывается из selfcheck; >=5 юнит-тестов." \
  --check "cargo test -p devh --lib core::guards::identity_guard"

echo "=== DONE ==="
